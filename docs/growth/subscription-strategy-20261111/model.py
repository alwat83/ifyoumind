"""Reproduce the pricing decision tables with Python 3.9+, using no services."""
import argparse
import math
from dataclasses import dataclass


@dataclass(frozen=True)
class Plan:
    label: str
    price: float
    reports: int


@dataclass(frozen=True)
class Assumptions:
    card_rate: float = 0.029
    billing_rate: float = 0.007
    fixed_payment_fee: float = 0.30
    failure_rate: float = 0.02
    refund_rate: float = 0.01
    dispute_rate: float = 0.001
    dispute_fee: float = 15.00
    support: float = 0.35
    shared_delivery: float = 0.15
    report_cost: float = 0.50


HYPOTHESIS = (
    Plan('Proposed Starter', 3.99, 1),
    Plan('Proposed Plus', 7.99, 3),
    Plan('Proposed Pro', 14.99, 8),
)
PILOT = (Plan('Pilot Starter', 4.99, 1), Plan('Pilot Plus', 9.99, 3))
MIX = (0.70, 0.30)
USAGE = (0.25, 0.60, 1.00)


def recurring_cash(plan, a):
    return plan.price * (1 - a.failure_rate) * (1 - a.refund_rate - a.dispute_rate)


def payment_costs(plan, a):
    collected = 1 - a.failure_rate
    card = collected * (plan.price * a.card_rate + a.fixed_payment_fee)
    billing = collected * plan.price * a.billing_rate
    disputes = collected * a.dispute_rate * a.dispute_fee
    return card, billing, disputes


def contribution(plan, usage, a, report_cost=None):
    cost = a.report_cost if report_cost is None else report_cost
    return (recurring_cash(plan, a) - sum(payment_costs(plan, a))
            - a.support - a.shared_delivery - usage * plan.reports * cost)


def blended(values):
    return sum(value * weight for value, weight in zip(values, MIX))


def dollars(value):
    return f'-${abs(value):,.2f}' if value < 0 else f'${value:,.2f}'


def row(*cells):
    print('| ' + ' | '.join(map(str, cells)) + ' |')


def table(*columns):
    row(*columns)
    row(*(['---'] * len(columns)))


def render(a):
    print('# Modeled subscription scenarios\n')
    print('Generated by model.py. USD. Amounts per billed subscriber-month unless stated.\n')
    print(f'Report cost in base case: {dollars(a.report_cost)}. Usage: 25%, 60%, and 100% of credits. '
          'Margin uses gross billed subscription price as the denominator.\n')
    print('## Pricing and usage\n')
    table('Plan', 'Price', 'Reports', 'Net receipts', 'Card fee', 'Billing fee', 'Dispute fee',
          'Report cost low / expected / full', 'Low contribution', 'Expected contribution', 'Full contribution')
    for plan in HYPOTHESIS + PILOT:
        unit_costs = ' / '.join(dollars(plan.reports * u * a.report_cost) for u in USAGE)
        margins = [f'{dollars(v)} ({v / plan.price:.1%})' for v in
                   (contribution(plan, u, a) for u in USAGE)]
        row(plan.label, dollars(plan.price), plan.reports, dollars(recurring_cash(plan, a)),
            *(dollars(x) for x in payment_costs(plan, a)), unit_costs, *margins)

    print('\n## Full-usage sensitivity and cost ceiling\n')
    table('Plan', '$0.20/report', '$0.50/report', '$1/report', '$1.50/report', '$2/report',
          'Break-even cost per report', 'Cost per report at 60% margin')
    for plan in HYPOTHESIS + PILOT:
        before_report = contribution(plan, 0, a)
        row(plan.label, *(dollars(contribution(plan, 1, a, c)) for c in (0.20, 0.50, 1, 1.50, 2)),
            dollars(before_report / plan.reports),
            dollars((before_report - 0.60 * plan.price) / plan.reports))

    arpu = blended([p.price for p in PILOT])
    receipts = blended([recurring_cash(p, a) for p in PILOT])
    expected = blended([contribution(p, USAGE[1], a) for p in PILOT])
    full = blended([contribution(p, 1, a) for p in PILOT])
    allowance = blended([p.reports for p in PILOT])
    print('\n## Subscriber scale at a 70% Starter and 30% Plus mix\n')
    table('Billed accounts', 'Gross MRR', 'Net receipts', 'Expected / max reports',
          'Expected contribution', 'Full contribution', 'Replacements / month', 'After replacement CAC')
    for count in (100, 500, 1000, 5000, 10000):
        replacements = count * 0.06
        row(f'{count:,}', dollars(count * arpu), dollars(count * receipts),
            f'{count * allowance * USAGE[1]:,.0f} / {count * allowance:,.0f}',
            f'{dollars(count * expected)} ({expected / arpu:.1%})',
            f'{dollars(count * full)} ({full / arpu:.1%})',
            f'{replacements:,.0f}', dollars(count * expected - replacements * 15))

    print('\n## Acquisition and retention sensitivity\n')
    table('Scenario', 'Monthly churn', 'CAC', 'Monthly contribution', 'Simple contribution LTV',
          'LTV / CAC', 'Payback')
    for label, churn, cac, unit_cost, usage in (
        ('Lean', 0.03, 8, 0.20, 0.25), ('Base', 0.06, 15, a.report_cost, 0.60),
        ('Stress', 0.12, 35, 1.50, 1.00),
    ):
        value = blended([contribution(p, usage, a, unit_cost) for p in PILOT])
        ltv = value / churn
        row(label, f'{churn:.0%}', dollars(cac), dollars(value), dollars(ltv),
            f'{ltv / cac:.1f}×', f'{cac / value:.1f} months' if value > 0 else 'None')
    after_cac = expected - 0.06 * 15
    if after_cac > 0:
        print(f'\nAt {dollars(after_cac)} contribution per account after replacement CAC, '
              f'a modeled $500 monthly fixed cost would need {math.ceil(500 / after_cac)} accounts. '
              'Taxes and owner compensation are outside this illustration.')
    else:
        print('\nReplacement CAC exhausts contribution. No subscriber count covers fixed costs under these assumptions.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--report-cost', type=float, default=0.50)
    args = parser.parse_args()
    if not math.isfinite(args.report_cost) or args.report_cost < 0:
        parser.error('report cost must be finite and nonnegative')
    render(Assumptions(report_cost=args.report_cost))
